            KOrthoInt(0, 10) = invVol * ((-d01 + d55)*dSqhw)/12.;
            KOrthoInt(0, 11) = invVol * ((d02 + d44)*hSqdw)/24.;
            KOrthoInt(0, 12) = invVol * (d00*dSqhSq + d55*dSqwSq - 2*d44*hSqwSq)/18.;
            KOrthoInt(0, 13) = invVol * ((d01 + d55)*dSqhw)/24.;
            KOrthoInt(0, 14) = invVol * ((-d02 + d44)*hSqdw)/12.;
            KOrthoInt(0, 15) = invVol * (-2*d00*dSqhSq + d55*dSqwSq - 2*d44*hSqwSq)/36.;
            KOrthoInt(0, 16) = invVol * ((d01 - d55)*dSqhw)/24.;
            KOrthoInt(0, 17) = invVol * -((d02 + d44)*hSqdw)/12.;
            KOrthoInt(0, 18) = invVol * (-(d00*dSqhSq) - d55*dSqwSq - d44*hSqwSq)/36.;
            KOrthoInt(0, 19) = invVol * -((d01 + d55)*dSqhw)/24.;
            KOrthoInt(0, 20) = invVol * -((d02 + d44)*hSqdw)/24.;
            KOrthoInt(0, 21) = invVol * (d00*dSqhSq - 2*(d55*dSqwSq + d44*hSqwSq))/36.;
            KOrthoInt(0, 22) = invVol * ((-d01 + d55)*dSqhw)/24.;
            KOrthoInt(0, 23) = invVol * ((-d02 + d44)*hSqdw)/24.;
