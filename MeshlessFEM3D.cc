        KOrtho(4, 4) += weight * (d55*(dxp1*dxp1) + d11*(dyp1*dyp1) + d33*(dzp1*dzp1));
        KOrtho(4, 5) += weight * ((d12 + d33)*dyp1*dzp1);
        KOrtho(4, 6) += weight * (d01*dxp2*dyp1 + d55*dxp1*dyp2);
