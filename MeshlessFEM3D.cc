        KOrtho(4, 11) += weight * (d33*dyp3*dzp1 + d12*dyp1*dzp3);
        KOrtho(4, 12) += weight * (d01*dxp4*dyp1 + d55*dxp1*dyp4);
        KOrtho(4, 13) += weight * (d55*dxp1*dxp4 + d11*dyp1*dyp4 + d33*dzp1*dzp4);
        KOrtho(4, 14) += weight * (d33*dyp4*dzp1 + d12*dyp1*dzp4);
        KOrtho(4, 15) += weight * (d01*dxp5*dyp1 + d55*dxp1*dyp5);
